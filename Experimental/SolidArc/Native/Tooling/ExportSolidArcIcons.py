#====================================================================================================================================
#                                                     EXPORTSOLIDARCICONS.PY
#====================================================================================================================================
# 🧩 Writes the HTML SolidArc icon paths (src/WorkspacePanel.js `Paths`) as IconArt SVG files and their symbol list
#
#    EngineContent/Icons/SolidArc/<name>.svg      24 × 24 view box, white stroke 1.45 (WorkspacePanel.css `svg`), tinted on draw
#    Engine/Interface/Icons/SolidArcSymbols.inc  FRONTIER_ICON(SolidArc<Name>, "SolidArc/<name>.svg"), IconDomain::SolidArc
#
#    Run from the repository root:  python3 Experimental/SolidArc/Native/Tooling/ExportSolidArcIcons.py

import pathlib
import re

#------------------------------------------------------------------------------------------------------------------------
#                                                    CONSTANTS
#------------------------------------------------------------------------------------------------------------------------

Root      = pathlib.Path(__file__).resolve().parents[4]
Source    = Root / 'Experimental/SolidArc/src/WorkspacePanel.js'
Artwork   = Root / 'EngineContent/Icons/SolidArc'
Catalogue = Root / 'Engine/Interface/Icons/SolidArcSymbols.inc'
Opening   = ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#ffffff" '
             'stroke-width="1.45" stroke-linecap="round" stroke-linejoin="round">')

#------------------------------------------------------------------------------------------------------------------------
#                                                    FUNCTIONS
#------------------------------------------------------------------------------------------------------------------------

def ReadPaths():
    Text  = Source.read_text(encoding='utf-8')
    Block = Text[Text.index('const Paths = {'):Text.index('};', Text.index('const Paths = {'))]
    Paths = {}
    for Match in re.finditer(r"^\s*([a-z0-9]+)\s*:\s*((?:'[^']*'\s*\+?\s*)+)", Block, re.M):
        Paths[Match.group(1)] = ''.join(re.findall(r"'([^']*)'", Match.group(2)))
    return Paths

def SymbolName(Name):
    return 'SolidArc' + Name[:1].upper() + Name[1:]

def Main():
    Paths = ReadPaths()
    Artwork.mkdir(parents=True, exist_ok=True)
    Lines = ['// Generated by Experimental/SolidArc/Native/Tooling/ExportSolidArcIcons.py from the HTML SolidArc icon paths.',
             '// SolidArc workspace only (IconDomain::SolidArc). Shared editor chrome is inherited, not copied.']
    for Name, Body in sorted(Paths.items()):
        (Artwork / f'{Name}.svg').write_text(Opening + Body + '</svg>\n', encoding='utf-8')
        Lines.append(f'FRONTIER_ICON({SymbolName(Name)}, "SolidArc/{Name}.svg")')
    Catalogue.write_text('\n'.join(Lines) + '\n', encoding='utf-8')
    print(f'{len(Paths)} icons → {Artwork.relative_to(Root)}, {Catalogue.relative_to(Root)}')

if __name__ == '__main__':
    Main()
